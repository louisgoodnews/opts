const fn row(
    name: &'static str,
    unit: &'static str,
    source: Source,
    kind: Kind,
    shared: bool,
    live: bool,
) -> InputRow {
    InputRow {
        name,
        unit,
        source,
        kind,
        shared,
        live,
    }
}

